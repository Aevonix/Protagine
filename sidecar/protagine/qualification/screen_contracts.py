def apply_contracts(cases):
    """Opt in after configured output budgets are materialized; no native forcing."""
    result = []
    for case in cases:
        if case.boundary != 'role_completion':
            result.append(case)
            continue
        if case.consumer != 'role_completion' or case.id not in SCHEMAS:
            raise ValueError('No independently authored screening contract for ' + case.id)
        response_schema = {'name': 'screen_answer', 'schema': deepcopy(SCHEMAS[case.id])}
        result.append(replace(case, version=case.version + '-json-schema-v1',
            consumer='screen_schema_completion', evaluator='screen_schema_fields',
            inputs={**deepcopy(case.inputs), 'response_schema': response_schema},
            required_capabilities=(*case.required_capabilities, 'supports_json_schema')))
    return result


async def consume(inputs, context):
    observed = await schema_completion(inputs, context)
    # This is the trusted consumer's input contract, not a model-supplied schema.
    observed['effects']['output_schema'] = deepcopy(inputs['response_schema']['schema'])
    return observed


def assess(observed, oracle):
    import jsonschema
    effects = observed.get('effects', {})
    requests = effects.get('serialized_requests', [])
    checks = {**json_fields(observed, oracle),
        'schema_in_serialized_request': bool(requests) and all(
            row.get('response_format_matches') is True for row in requests),
        'output_satisfies_schema': False}
    try:
        output = json.loads(observed.get('output', ''))
        schema = effects.get('output_schema')
        if not isinstance(schema, dict):
            return checks
        jsonschema.validate(output, schema)
    except (ValueError, TypeError, jsonschema.ValidationError, jsonschema.SchemaError):
        return checks
    checks['output_satisfies_schema'] = True
    return checks


CONSUMERS = {'screen_schema_completion': consume}
EVALUATORS = {'screen_schema_fields': assess}
