def _type(name, *, nullable=False):
    return {'type': [name, 'null'] if nullable else name}


def _fields(names, kind, *, nullable=False):
    return {name: _type(kind, nullable=nullable) for name in names.split()}


def _enum(*values, nullable=False):
    return {**_type('string', nullable=nullable), 'enum': [*values, *([None] if nullable else [])]}


